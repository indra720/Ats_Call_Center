export interface LeadItem {
  id: string;
  name: string;
  email: string;
  phone: string;
  company: string;
  source: 'Website' | 'Google Ads' | 'Facebook' | 'Referral' | 'Cold Call' | 'WhatsApp' | 'Email' | 'Walk-in';
  stage: 'New' | 'Contacted' | 'Qualified' | 'Proposal' | 'Negotiation' | 'Converted' | 'Lost';
  assignedToId: string;
  assignedToName: string;
  teamId: string;
  score: number;
  dealValue: number;
  createdAt: string;
  lastContacted: string;
  city: string;
  notesCount: number;
}

export interface CallLogItem {
  id: string;
  callerName: string;
  customerName: string;
  company: string;
  phoneNumber: string;
  direction: 'inbound' | 'outbound';
  status: 'Completed' | 'Missed' | 'Voicemail' | 'Failed';
  durationSeconds: number;
  callDate: string;
  recordingUrl: string;
  agentId: string;
  agentName: string;
  teamId: string;
  sentiment: 'Positive' | 'Neutral' | 'Negative';
  leadScoreImpact: number;
}

